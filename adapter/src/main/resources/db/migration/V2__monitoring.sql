alter table instance
    add column internal_url varchar(2048);

comment on column instance.internal_url is 'URL on which other LOCAL instances reach a LOCAL instance';

create table activity_event
(
    id          uuid primary key,
    occurred_at timestamp with time zone not null,
    severity    varchar(16)              not null,
    source_type varchar(32)              not null,
    source_id   uuid                     not null,
    source_name varchar(255)             not null,
    title       varchar(255)             not null,
    detail      varchar(2048)
);

create index ix_activity_event_time on activity_event (occurred_at desc);

comment on table activity_event is 'What happened to the instances; outlives the instances themselves';

create table ingest_sample
(
    id               bigint generated by default as identity primary key,
    instance_id      uuid                     not null references instance (id) on delete cascade,
    sampled_at       timestamp with time zone not null,
    ingested_members bigint                   not null
);

create index ix_ingest_sample_time on ingest_sample (sampled_at);

comment on table ingest_sample is 'Members ingested by an LDES server so far, sampled to derive its throughput';
